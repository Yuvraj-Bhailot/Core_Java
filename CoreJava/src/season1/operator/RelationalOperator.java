package season1.operator;

public class RelationalOperator {
	public static void main(String[] args) {
		// relational operator/Comparison
		
		double num1=10.0;
		double num2=25.10;
		
		System.out.println("num1("+num1+") > num2("+num2+"): " + (num1>num2));
		System.out.println("num1("+num1+") < num2("+num2+"): " + (num1<num2));
		System.out.println("num1("+num1+") >= num2("+num2+"): " + (num1>=num2));
		System.out.println("num1("+num1+") <= num2("+num2+"): " + (num1<=num2));
		System.out.println("num1("+num1+") == num2("+num2+"): " + (num1==num2));
		System.out.println("num1("+num1+") != num2("+num2+"): " + (num1!=num2));
	}
}
